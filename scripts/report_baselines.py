#!/usr/bin/env python
"""Our models against GraphCast and ClimODE on the ERA5 2020 GraphCast protocol
(감자 21:09 / 21:35 KST 11/01: every new model result gets this comparison).

    python scripts/report_baselines.py --models "N1-T=runs/stage15/N1T/compare_graphcast_2020.json" \
        "N1 cold=runs/physics_n1/compare_graphcast_2020.json" --ratio N1-T \
        --title "Stage 15 N1-T against GraphCast and ClimODE (2020)" --out docs/results/.../baselines.md

Inputs: scripts/compare_graphcast.py (or compare_memory.py) outputs with the rows 'model',
'graphcast', 'persistence', 'climatology'. GraphCast, persistence and climatology come from
the first file. ClimODE (and its table's other models) are the published numbers of ClimODE's
Table 6 (Verma, Heinonen & Garg, ICLR 2024; WeatherBench 5.625 deg, test 2017-2018): other
years, leads to 36 h only.
"""
import argparse
import json

import numpy as np

VARS = (("z500", "geopotential@500"), ("t850", "temperature@850"), ("t2m", "2m_temperature"),
        ("u10", "10m_u_component_of_wind"), ("v10", "10m_v_component_of_wind"))
LEADS = (6, 12, 18, 24, 36, 72, 120)
CLIMODE = {"z500": {6: 103, 12: 135, 18: 163, 24: 193, 36: 260},
           "t850": {6: 1.16, 12: 1.32, 18: 1.47, 24: 1.55, 36: 1.75},
           "t2m": {6: 1.21, 12: 1.45, 18: 1.43, 24: 1.40, 36: 1.70},
           "u10": {6: 1.41, 12: 1.81, 18: 1.97, 24: 2.01, 36: 2.25},
           "v10": {6: 1.53, 12: 1.81, 18: 1.96, 24: 2.04, 36: 2.29}}


def rmse(rows, var, lead):
    for r in rows:
        if r["variable"] == var and r["lead_h"] == lead:
            return r["rmse"]
    return float("nan")


def fmt(x):
    if x is None or not np.isfinite(x):
        return "-"
    return f"{x:.4g}"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--models", nargs="+", required=True, help="LABEL=compare json")
    ap.add_argument("--ratio", default=None, help="label whose ratios to GraphCast and ClimODE are shown (default: first)")
    ap.add_argument("--title", default="Our models against GraphCast and ClimODE (2020)")
    ap.add_argument("--note", default="")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    data = {}
    for spec in args.models:
        label, path = spec.split("=", 1)
        with open(path) as f:
            data[label] = json.load(f)
    ref = next(iter(data.values()))
    main_label = args.ratio or next(iter(data))
    labels = list(data)
    lines = [f"# {args.title}", "",
             "Latitude-weighted RMSE in physical units, means over the 31 initialisations of the GraphCast protocol in 2020 "
             "(every 12 days, 00 UTC; held out for every model of ours). GraphCast = the WeatherBench-2 forecast coarsened "
             "to 5.625 deg. ClimODE = the published numbers of ClimODE's Table 6 (Verma, Heinonen & Garg, ICLR 2024; "
             "WeatherBench 5.625 deg, test 2017-2018), so other years and leads to 36 h only. "
             "Generated by `scripts/report_baselines.py`." + (f" {args.note}" if args.note else ""), "",
             "| variable | lead | GraphCast | " + " | ".join(labels) + " | persistence | climatology | ClimODE (pub.) | "
             f"{main_label} / GraphCast | {main_label} / ClimODE |",
             "|---" * (len(labels) + 8) + "|"]
    for short, var in VARS:
        for lead in LEADS:
            gc = rmse(ref["graphcast"], var, lead)
            vals = [rmse(d["model"], var, lead) for d in data.values()]
            mine = rmse(data[main_label]["model"], var, lead)
            cl = CLIMODE[short].get(lead)
            lines.append(f"| {short} | {lead} h | {fmt(gc)} | " + " | ".join(fmt(v) for v in vals)
                         + f" | {fmt(rmse(ref['persistence'], var, lead))} | {fmt(rmse(ref['climatology'], var, lead))} | "
                         + f"{fmt(cl) if cl else '-'} | {mine / gc:.2f}x | " + (f"{mine / cl:.2f}x |" if cl else "- |"))
    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
