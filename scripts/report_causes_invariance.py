"""Does a fine-tuned model keep N1's causal structure? (감자 18:21 KST 11/01 "인과성의 판단은?")

    python scripts/report_causes_invariance.py --ref N1=runs/physics_n1/causes_2020.json \
        --models D-noactor=runs/stage10_Dnoactor/causes_2020.json E2=runs/stage13_E2/causes_2020.json \
        --out docs/results/stage10_memory/causes_memory.md

Inputs: scripts/eval_physics_causes.py on the same initialisations. Per
intervention (arrow cut of the coupled-climate diagram, §9.2) the all-variable
MSE change of the cut model vs the intact one at 24 / 72 h (+ = cutting hurts,
i.e. the pathway helps), and the sign agreement with the reference on the
significant per-variable changes. The summary is report_physics_causes.invariance
(sign agreement, rank correlation of |change| at 72 h); the reference's own
2018 / 2020 invariance is the yardstick.
"""

import argparse
import json
import os

import numpy as np

from report_physics_causes import _li, _sig, invariance


def _load(spec):
    label, path = spec.split("=", 1)
    with open(path) as f:
        return label, json.load(f)


def _chg(res, s, h):
    v = s.get("change_all", {}).get("mean", [None] * len(res["leads_h"]))[_li(res, h)]
    return "blown" if v is None or not np.isfinite(v) else f"{100 * v:+.1f}%"


def _agree(ref, a, res, b):
    ag = n = 0
    for k in ref["keys"]:
        for h in (24, 72):
            ga, gb = _sig(a["change"][k], _li(ref, h)), _sig(b["change"][k], _li(res, h))
            if ga and gb:
                n += 1
                ag += ga == gb
    return f"{ag}/{n}" if n else "–"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--ref", required=True, help="LABEL=causes.json (the reference model)")
    ap.add_argument("--ref-other-year", default=None, help="the reference on another year (yardstick)")
    ap.add_argument("--models", nargs="+", required=True, help="LABEL=causes.json")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    rl, ref = _load(args.ref)
    models = [_load(m) for m in args.models]
    lines = [f"# Causal structure vs {rl} ({ref.get('year')}, {len(ref['init_times'])} initialisations)", "",
             "Generated by `scripts/report_causes_invariance.py`. Change = all-variable MSE of the cut model vs "
             "the intact one (+ = cutting hurts, the pathway helps; − = the pathway hurts). Agree = sign agreement "
             f"with {rl} on significant per-variable changes at 24 / 72 h.", "",
             "## Summary", "", "| Model | sign agreement | pairs | rank corr. of abs. change 72 h | interventions |",
             "|---|---|---|---|---|"]
    if args.ref_other_year:
        ol, other = _load(args.ref_other_year)
        a, n, rho, m = invariance(other, ref)
        lines.append(f"| {ol} (yardstick) | {100 * a:.0f}% | {n} | {rho:.2f} | {m} |")
    for label, res in models:
        a, n, rho, m = invariance(ref, res)
        lines.append(f"| {label} | {100 * a:.0f}% | {n} | {rho:.2f} | {m} |")
    head = f"| Intervention | {rl} 24 h | {rl} 72 h | " + " | ".join(
        f"{lb} 24 h | {lb} 72 h | agree" for lb, _ in models) + " |"
    lines += ["", "## Per intervention", "", head, "|" + "---|" * (3 + 3 * len(models))]
    for name, a in ref["interventions"].items():
        if name == "full" or "change_all" not in a:
            continue
        row = [name, _chg(ref, a, 24), _chg(ref, a, 72)]
        for _, res in models:
            b = res["interventions"].get(name)
            if b is None or "change_all" not in b:
                row += ["–", "–", "–"]
            else:
                row += [_chg(res, b, 24), _chg(res, b, 72), _agree(ref, a, res, b)]
        lines.append("| " + " | ".join(row) + " |")
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
