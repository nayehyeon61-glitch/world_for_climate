"""Stage 14 board 2 with the memory model (chain 18): rules S1, S2, S4 from the response evaluations.

Inputs are `scripts/train_speedy_game.py eval` outputs (`response.json`): per (1984 branch point, action) the true
SPEEDY response (one branch minus the nature run) and the model's (forecast with minus without the action), late
window (second half of the 120 h run). gain = 1 - rmse(model - truth) / rmse(truth) (+ = better than a zero response).

S1  a game-trained model beats the same-sample nature control by >= 20% on the held-out SST actions, pattern corr >= 0.5
S2  the learning-progress experimenter beats the random one by >= 5% at the same number of SPEEDY runs
S4  sign agreement >= 70% and pattern corr >= 0.5 (held-out SST and global forcings)

usage: python scripts/report_memory_game.py --responses M_adapt=.../response.json M_lp=... M_random=... M_nature=... \
           --control M_nature --lp M_lp --random M_random --out docs/results/stage14_simulator/board2_memory.md
"""
import argparse
import json
import os

import numpy as np

KEYS = (("t850", "temperature@850"), ("z500", "geopotential@500"), ("t2m", "2m_temperature"),
        ("msl", "mean_sea_level_pressure"), ("u850", "u_component_of_wind@850"))


def subsets(rows):
    return {"held-out SST": [r for r in rows if r["held_out"] and r["action"].startswith("sst")],
            "global": [r for r in rows if not r["action"].startswith("sst")]}


def finite(r, key="temperature@850"):
    return np.isfinite(r[key]["rmse"])


def stats(rows, key):
    rows = [r for r in rows if finite(r)]
    ok = [r for r in rows if r[key]["rmse_zero"] > 0]
    gain = 1 - np.mean([r[key]["rmse"] for r in ok]) / np.mean([r[key]["rmse_zero"] for r in ok]) if ok else np.nan
    return gain, np.nanmean([r[key]["corr"] for r in rows]), np.nanmean([r[key]["sign"] for r in rows])


def paired_gain(rows_a, rows_b, key, rng, n=4000):
    """1 - rmse_a / rmse_b over the pairs both have, with a bootstrap 95% interval over pairs."""
    b = {(r["init"], r["action"]): r[key]["rmse"] for r in rows_b if finite(r)}
    pairs = [(r[key]["rmse"], b[(r["init"], r["action"])]) for r in rows_a
             if finite(r) and (r["init"], r["action"]) in b]
    if not pairs:
        return np.nan, np.nan, np.nan, 0
    x = np.array(pairs)
    g = 1 - x[:, 0].mean() / x[:, 1].mean()
    idx = rng.integers(0, len(x), (n, len(x)))
    bs = 1 - x[idx, 0].mean(1) / x[idx, 1].mean(1)
    return g, np.percentile(bs, 2.5), np.percentile(bs, 97.5), len(x)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--responses", nargs="+", required=True, metavar="LABEL=PATH")
    p.add_argument("--control", default="M_nature")
    p.add_argument("--lp", default="M_lp")
    p.add_argument("--random", default="M_random")
    p.add_argument("--out", required=True)
    a = p.parse_args()
    data = {}
    for spec in a.responses:
        lab, path = spec.split("=", 1)
        if os.path.exists(path):
            with open(path) as f:
                data[lab] = json.load(f)
    rng = np.random.default_rng(0)
    L = ["# Stage 14 board 2 with the memory model: intervention responses (1984, held out)", "",
         "Generated by `scripts/report_memory_game.py`. Models: M_adapt = E2 (N1 + memory + energy-neutral corrector) "
         "adapted to SPEEDY 1982-83 with the continuous filter; M_<arm> = M_adapt after 150 game updates from the filled "
         "1982-84 memory with that experimenter (lp = learning progress, random, nature = the same windows without "
         "interventions, the S1 control). Truth = one SPEEDY branch minus the nature run (it carries the chaotic part, "
         "cf. the 14.2 SNR diagnosis); scores on the late window (second half of 120 h). gain = 1 - rmse(error) / "
         "rmse(truth), + = better than a zero response. Blown = branch points whose 120 h free run blew up (their pairs "
         "are left out; paired comparisons use the pairs finite in both).", ""]
    for name, rows in subsets(next(iter(data.values()))["rows"]).items():
        L += [f"## {name} ({len(rows)} pairs per model)", "",
              "| model | blown points | " + " | ".join(f"{s} gain / corr / sign" for s, _ in KEYS) + " |",
              "|---" * (len(KEYS) + 2) + "|"]
        for lab, d in data.items():
            rs = subsets(d["rows"])[name]
            pts = {r["init"] for r in rs}
            blown = {r["init"] for r in rs if not finite(r)}
            L.append(f"| {lab} | {len(blown)}/{len(pts)} | " + " | ".join("{:+.1%} / {:+.2f} / {:.2f}".format(*stats(rs, k)) for _, k in KEYS) + " |")
        L.append("")
    L += ["## Decision rules", ""]
    held = {lab: subsets(d["rows"])["held-out SST"] for lab, d in data.items()}
    glob = {lab: subsets(d["rows"])["global"] for lab, d in data.items()}
    key = "temperature@850"
    if a.control in data:
        for lab in data:
            if lab in (a.control, "M_adapt"):
                continue
            g = paired_gain(held[lab], held[a.control], key, rng)
            corr = stats(held[lab], key)[1]
            ok = g[0] >= 0.20 and corr >= 0.5
            L.append(f"- **S1** {lab} vs {a.control} (held-out SST, t850 response error): {g[0]:+.1%} "
                     f"[{g[1]:+.1%}, {g[2]:+.1%}] (n={g[3]}), pattern corr {corr:.2f} → "
                     f"{'supported' if ok else 'not supported'} (needs >= +20% and corr >= 0.5)")
    else:
        L.append(f"- **S1** waits for the control {a.control}.")
    if a.lp in data and a.random in data:
        g = paired_gain(held[a.lp], held[a.random], key, rng)
        L.append(f"- **S2** {a.lp} vs {a.random} at the same 150 updates (held-out SST, t850): {g[0]:+.1%} "
                 f"[{g[1]:+.1%}, {g[2]:+.1%}] (n={g[3]}) → {'supported' if g[0] >= 0.05 and g[1] > 0 else 'not supported'}")
    for lab in data:
        cs = [stats(held[lab], k) for _, k in KEYS] + [stats(glob[lab], k) for _, k in KEYS]
        corr, sign = np.nanmean([c[1] for c in cs]), np.nanmean([c[2] for c in cs])
        L.append(f"- **S4** {lab}: mean pattern corr {corr:.2f}, sign agreement {sign:.2f} over the {len(KEYS)} "
                 f"channels x (held-out SST, global) → {'supported' if corr >= 0.5 and sign >= 0.7 else 'not supported'}")
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
