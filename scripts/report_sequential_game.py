#!/usr/bin/env python
"""Stage 14.2 board 4 report: rules G1-G4 (README_KO section 14.2).

    python scripts/report_sequential_game.py --evals runs/stage14_2/eval_A/forced_response.json \
        runs/stage14_2/eval_B/forced_response.json --runs runs/stage14_2 \
        --era5 N1-T=runs/stage15/N1T/compare_graphcast_2020.json policy=runs/stage14_2/policy/compare_graphcast_2020.json \
        --out docs/results/stage14_simulator/board4.md

G1: forced-response error of the students (relative to the forced target's power + noise; 1 =
no better than zero response at the noise level) on the held-out SST sites, policy vs random and
bandit, paired bootstrap over (point, action). G2: does the single-branch arm drift towards
actions whose response is mostly chaos (low forced share 'kept') during training? G3: noctx vs
policy. G4: ERA5 2020 RMSE of the students vs N1-T on the GraphCast protocol.
"""
import argparse
import json
import os

import numpy as np

ARMS = ("policy", "random", "bandit", "single", "noctx")
LABEL = {"start": "N1-T (start)"}
VARS = (("z500", "geopotential@500"), ("t850", "temperature@850"), ("t2m", "2m_temperature"))


def boot(diff, n=2000, seed=0):
    rng = np.random.default_rng(seed)
    d = np.asarray(diff)
    idx = rng.integers(len(d), size=(n, len(d)))
    m = d[idx].mean(1)
    return float(d.mean()), float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def merged_rows(paths):
    rows = {}
    for p in paths:
        with open(p) as f:
            res = json.load(f)
        for r in res["rows"]:
            key = (r["init"], r["action"])
            rows.setdefault(key, {k: v for k, v in r.items() if not isinstance(v, dict)})
            for lab, v in r.items():
                if isinstance(v, dict):
                    rows[key][lab] = v
    return list(rows.values())


def gain(rows, a, b):
    """Paired relative gain of model a over model b (+ = a better)."""
    ok = [r for r in rows if a in r and b in r and np.isfinite(r[a]["rel_error"]) and np.isfinite(r[b]["rel_error"])]
    if not ok:
        return None
    ea = np.array([r[a]["rel_error"] for r in ok])
    eb = np.array([r[b]["rel_error"] for r in ok])
    g, lo, hi = boot(1 - ea / eb)
    return g, lo, hi, len(ok)


def pct(x):
    return "-" if x is None else f"{100 * x[0]:+.1f}% [{100 * x[1]:+.1f}, {100 * x[2]:+.1f}] (n={x[3]})"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--evals", nargs="+", required=True)
    ap.add_argument("--runs", required=True, help="directory with ARM/seq_history.json")
    ap.add_argument("--era5", nargs="*", default=[], help="LABEL=compare_graphcast json; the first is the reference")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    rows = merged_rows(args.evals)
    models = [m for m in ("start",) + ARMS if any(m in r for r in rows)]
    sst = [r for r in rows if r["action"].startswith("sst")]
    glob = [r for r in rows if not r["action"].startswith("sst")]
    L = ["# Stage 14.2 board 4: the sequential intervention game", "",
         "Generated by `scripts/report_sequential_game.py`. Students start from N1-T (stage 15) and play 20 episodes "
         "(80 decisions) in randomized SPEEDY worlds; arms: policy (sequential, state-conditioned), random, bandit "
         "(context-free, immediate reward), single (policy with the single-branch target), noctx (policy without the "
         "state features). Error = forced-response error relative to the target's power + noise (1984, 6 branch points, "
         "48 h, 5 members; zero response scores `zero`).", ""]
    # training summary
    L += ["## Training", "", "| arm | decisions | mean reward | SST share | forced share of chosen (first / second half) | "
          "SNR of chosen (first / second half) | final p max | policy weights |", "|---|---|---|---|---|---|---|---|"]
    hists = {}
    for a in ARMS:
        p = os.path.join(args.runs, a, "seq_history.json")
        if not os.path.exists(p):
            continue
        with open(p) as f:
            h = json.load(f)["history"]
        hists[a] = h
        n = len(h["action"])
        half = n // 2
        kept, snr = np.array(h["kept"]), np.array(h["snr"])
        sst_share = np.mean([x.startswith("sst") for x in h["action"]])
        w = h.get("policy_w", {})
        wtxt = ", ".join(f"{k} {v:+.2f}" for k, v in w.items() if abs(v) > 1e-9) or "-"
        L.append(f"| {a} | {n} | {np.nanmean(h['reward']):+.4f} | {sst_share:.2f} | {kept[:half].mean():.2f} / "
                 f"{kept[half:].mean():.2f} | {snr[:half].mean():.2f} / {snr[half:].mean():.2f} | "
                 f"{h['probs_max'][-1]:.3f} | {wtxt} |")
    # G1 table
    L += ["", "## Forced-response error (1984, held out)", "",
          "| model | SST held-out sites | global forcings | all | skill vs zero (SST) | z500 / t850 / t2m pattern corr. (SST, late 24 h) |",
          "|---|---|---|---|---|---|"]
    zero_sst = np.mean([r["zero_error"] for r in sst]) if sst else float("nan")
    zero_glob = np.mean([r["zero_error"] for r in glob]) if glob else float("nan")
    L.append(f"| zero response | {zero_sst:.3f} | {zero_glob:.3f} | - | 0 | - |")
    for m in models:
        e = lambda rs: np.nanmean([r[m]["rel_error"] for r in rs if m in r]) if rs else float("nan")
        cor = [np.nanmean([r[m].get(k, np.nan) for r in sst if m in r]) for _, k in VARS]
        skill = 1 - e(sst) / zero_sst
        L.append(f"| {LABEL.get(m, m)} | {e(sst):.3f} | {e(glob):.3f} | {e(rows):.3f} | {skill:+.3f} | "
                 + " / ".join(f"{c:.2f}" for c in cor) + " |")
    snr_sst = np.mean([r["snr"] for r in sst]) if sst else float("nan")
    snr_glob = np.mean([r["snr"] for r in glob]) if glob else float("nan")
    L += ["", f"Mean SNR of the 5-member response (late 24 h): SST {snr_sst:.2f}, global {snr_glob:.2f}.", ""]
    # rules
    g_r, g_b = gain(sst, "policy", "random"), gain(sst, "policy", "bandit")
    g_c = gain(sst, "noctx", "policy")
    g_start = {a: gain(sst, a, "start") for a in ARMS}
    L += ["## Decision rules", ""]
    if g_r and g_b:
        ok = g_r[0] >= 0.05 and g_b[0] >= 0.05 and g_r[1] > 0 and g_b[1] > 0
        L.append(f"- **G1** policy >= 5% below random and bandit (SST held-out): vs random {pct(g_r)}, vs bandit "
                 f"{pct(g_b)} → {'supported' if ok else 'not supported'}")
    if "single" in hists and "policy" in hists:
        ks, kp = np.array(hists["single"]["kept"]), np.array(hists["policy"]["kept"])
        drift = ks[len(ks) // 2:].mean() - ks[:len(ks) // 2].mean()
        L.append(f"- **G2** single drifts to chaotic actions: forced share of its choices {ks[:len(ks) // 2].mean():.2f} → "
                 f"{ks[len(ks) // 2:].mean():.2f} (policy {kp[:len(kp) // 2].mean():.2f} → {kp[len(kp) // 2:].mean():.2f}) "
                 f"→ {'supported' if drift < 0 and ks[len(ks) // 2:].mean() < kp[len(kp) // 2:].mean() else 'not supported'}")
    if g_c:
        L.append(f"- **G3** noctx >= 3% worse than policy: noctx vs policy {pct(g_c)} → "
                 f"{'supported' if g_c[0] <= -0.03 else 'not supported'}")
    L.append("- Learning at all (each arm vs its N1-T start, SST held-out): "
             + "; ".join(f"{a} {pct(g)}" for a, g in g_start.items() if g))
    # G4
    if args.era5:
        data = {}
        for spec in args.era5:
            lab, p = spec.split("=", 1)
            if os.path.exists(p):
                with open(p) as f:
                    data[lab] = json.load(f)
        if len(data) > 1:
            ref_lab = next(iter(data))
            def rm(d, v, h):
                return next((r["rmse"] for r in d["model"] if r["variable"] == v and r["lead_h"] == h), np.nan)
            L += ["", "## ERA5 2020 (GraphCast protocol, 31 initialisations; + = better than " + ref_lab + ")", "",
                  "| model | " + " | ".join(f"{s} {h} h" for s, _ in VARS for h in (24, 72, 120)) + " | worst |",
                  "|---" * (2 + 3 * len(VARS)) + "|"]
            for lab, d in data.items():
                cells, worst = [], 0.0
                for s, v in VARS:
                    for h in (24, 72, 120):
                        x, r0 = rm(d, v, h), rm(data[ref_lab], v, h)
                        g = 1 - x / r0
                        worst = min(worst, g)
                        cells.append(f"{x:.4g} ({100 * g:+.1f}%)" if lab != ref_lab else f"{x:.4g}")
                L.append(f"| {lab} | " + " | ".join(cells) + f" | {100 * worst:+.1f}% |")
                if lab != ref_lab:
                    L.append(f"\n- **G4** {lab}: worst change {100 * worst:+.1f}% → "
                             f"{'supported' if worst >= -0.03 else 'not supported'} (limit −3%)\n")
    with open(args.out, "w") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
