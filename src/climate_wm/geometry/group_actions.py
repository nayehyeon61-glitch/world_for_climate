"""Lie group SO(3), its Lie algebra so(3), and their action on fields on S^2.

Why so(3)?  The Lie algebra so(3) ~ (R^3, x) is exactly the space of Killing
vector fields of the sphere: omega in so(3) generates the velocity field
u(p) = omega x p, i.e. a rigid rotation of the sphere. A *field* of algebra
elements omega(p) (one per shell-patch, blended smoothly) therefore describes
a locally-rigid advection of the atmospheric state:

  * the component of omega orthogonal to p moves the point p (transport),
  * the component along p spins the tangent plane at p (rotation of vector
    features, e.g. turning of the wind) without moving p.

Algebra elements can be added/averaged, group elements cannot, which is why
the generator predicts xi in so(3) and only the action uses exp(xi).

`SphereRotationAction` implements Phi_g for a node-wise field of rotations
g_i = exp(dt * omega_i) on a triangular mesh by a semi-Lagrangian step:

    Phi_g(h)(p_i) = h(g_i^{-1} p_i)
    Phi_g(V)(p_i) = g_i V(g_i^{-1} p_i)

with linear (gnomonic barycentric) interpolation at the departure point. It is
exactly the identity for g = e, and differentiable w.r.t. omega.
"""

from __future__ import annotations

import torch
from torch import Tensor, nn

from . import spherical_mesh
from .tangent_frames import project_tangent

_SMALL = 1e-4


def hat(w: Tensor) -> Tensor:
    """R^3 -> so(3): [..., 3] -> skew-symmetric [..., 3, 3]."""
    zero = torch.zeros_like(w[..., 0])
    wx, wy, wz = w.unbind(-1)
    return torch.stack([
        torch.stack([zero, -wz, wy], -1),
        torch.stack([wz, zero, -wx], -1),
        torch.stack([-wy, wx, zero], -1),
    ], -2)


def vee(m: Tensor) -> Tensor:
    """so(3) -> R^3."""
    return torch.stack([m[..., 2, 1], m[..., 0, 2], m[..., 1, 0]], -1)


def so3_exp(w: Tensor) -> Tensor:
    """Exponential map so(3) -> SO(3) (Rodrigues), stable near 0."""
    theta2 = (w * w).sum(-1)[..., None, None]
    theta = theta2.clamp_min(_SMALL ** 2).sqrt()
    small = theta2 < _SMALL ** 2
    a = torch.where(small, 1 - theta2 / 6 + theta2 ** 2 / 120,
                    torch.sin(theta) / theta)
    b = torch.where(small, 0.5 - theta2 / 24 + theta2 ** 2 / 720,
                    (1 - torch.cos(theta)) / theta.square())
    k = hat(w)
    eye = torch.eye(3, dtype=w.dtype, device=w.device).expand_as(k)
    return eye + a * k + b * (k @ k)


def so3_log(r: Tensor) -> Tensor:
    """Logarithm SO(3) -> so(3) as R^3 (valid for rotation angles < pi).

    Uses theta = atan2(sin, cos) with sin from the skew part, which is stable
    (and differentiable) near the identity.
    """
    w = 0.5 * vee(r - r.transpose(-1, -2))  # sin(theta) * axis
    cos = 0.5 * (r[..., 0, 0] + r[..., 1, 1] + r[..., 2, 2] - 1)
    s2 = (w * w).sum(-1)
    small = (s2 < _SMALL ** 2) & (cos > 0)
    sin = s2.clamp_min(_SMALL ** 4).sqrt()
    factor = torch.where(small, 1 + s2 / 6, torch.atan2(sin, cos) / sin)
    return factor[..., None] * w


def lie_bracket(a: Tensor, b: Tensor) -> Tensor:
    """[a, b] in so(3) ~ cross product in R^3."""
    return torch.cross(a, b, dim=-1)


def killing_field(omega: Tensor, p: Tensor) -> Tensor:
    """Velocity u(p) = omega x p generated by omega in so(3) (tangent at p)."""
    return torch.cross(omega, p.expand_as(omega), dim=-1)


def clamp_rotation(omega: Tensor, max_angle: float) -> Tensor:
    """Smoothly limits |omega| to `max_angle` (radians per step)."""
    norm = omega.norm(dim=-1, keepdim=True)
    scale = max_angle * torch.tanh(norm / max_angle) / norm.clamp_min(1e-12)
    return omega * torch.where(norm > 1e-12, scale, torch.ones_like(scale))


class SphereRotationAction(nn.Module):
    """Semi-Lagrangian action of a node-wise SO(3) field on mesh features."""

    def __init__(self, mesh: spherical_mesh.TriangularMesh, rings: int = 3):
        super().__init__()
        cand = spherical_mesh.vertex_neighborhood_faces(mesh, rings=rings)
        minv = spherical_mesh.face_inverse_matrices(mesh)
        self.register_buffer("pos", torch.tensor(mesh.vertices, dtype=torch.float32))
        self.register_buffer("faces", torch.tensor(mesh.faces, dtype=torch.long))
        self.register_buffer("cand", torch.tensor(cand, dtype=torch.long))
        self.register_buffer("cand_minv", torch.tensor(minv[cand], dtype=torch.float32))

    @property
    def num_nodes(self) -> int:
        return self.pos.shape[0]

    def departure_weights(self, rot: Tensor):
        """Vertex indices [B, N, 3] and weights [B, N, 3] at g_i^{-1} p_i."""
        q = torch.einsum("bnji,nj->bni", rot, self.pos)  # R^T p
        lam = torch.einsum("nkij,bnj->bnki", self.cand_minv, q)
        total = lam.sum(-1, keepdim=True)
        lam = lam / torch.where(total.abs() < 1e-12, torch.ones_like(total), total)
        score = torch.where(total.squeeze(-1) > 0, lam.min(-1).values,
                            torch.full_like(total.squeeze(-1), -1e9))
        best = score.argmax(-1)  # [B, N]
        weights = torch.gather(lam, 2, best[..., None, None].expand(-1, -1, 1, 3))
        weights = weights.squeeze(2).clamp_min(0.)
        weights = weights / weights.sum(-1, keepdim=True).clamp_min(1e-12)
        face = torch.gather(self.cand.expand(rot.shape[0], -1, -1), 2,
                            best[..., None]).squeeze(-1)
        return self.faces[face], weights, q

    def forward(self, h: Tensor, v: Tensor, rot: Tensor):
        """Applies Phi_g.

        Args:
          h: scalars [B, N, Cs].
          v: tangent vectors [B, N, Cv, 3].
          rot: rotations g_i [B, N, 3, 3].
        Returns:
          (h', v') with the same shapes.
        """
        b, n = h.shape[:2]
        verts, w, q = self.departure_weights(rot)
        idx = verts.reshape(b, n * 3)
        h_g = torch.gather(h, 1, idx[..., None].expand(-1, -1, h.shape[-1]))
        h_new = (h_g.reshape(b, n, 3, -1) * w[..., None]).sum(2)
        cv = v.shape[2]
        v_flat = v.reshape(b, n, cv * 3)
        v_g = torch.gather(v_flat, 1, idx[..., None].expand(-1, -1, cv * 3))
        v_q = (v_g.reshape(b, n, 3, cv, 3) * w[..., None, None]).sum(2)
        q_unit = q / q.norm(dim=-1, keepdim=True).clamp_min(1e-12)
        v_q = project_tangent(v_q, q_unit)
        v_new = torch.einsum("bnij,bncj->bnci", rot, v_q)
        v_new = project_tangent(v_new, self.pos.expand(b, -1, -1))
        return h_new, v_new
